#!/usr/bin/env bash
# Regenerate docs/TREE.md (repo layout without static/ contents); run by `ns`. README.md is handwritten.
set -euo pipefail

for cmd in fd as-tree; do
  command -v "$cmd" >/dev/null || { echo "Error: $cmd missing from PATH." >&2; exit 1; }
done

ROOT=$(git rev-parse --show-toplevel)
cd "$ROOT"
{
  echo '# Repository tree'
  echo
  echo '_Generated by `static/scripts/readme-tree-update.sh`; do not edit._'
  echo
  echo '```text'
  fd --exclude .git --exclude result --exclude 'static/*' | as-tree
  echo '```'
} >docs/TREE.md
echo "docs/TREE.md updated."
